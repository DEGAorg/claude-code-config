#!/usr/bin/env bash
set -euo pipefail

# Codex settings adapter
# Reads settings-template.json and generates two files for ~/.codex/:
#   config.toml  — MCP servers, model config, feature flags (managed block only)
#   hooks.json   — lifecycle hooks (Codex uses the same event names as Claude)
#
# config.toml is shared with the user, so it is NOT rewritten from scratch.
# TOML cannot be safely line-merged (a root key appended after a user [table]
# silently nests under it, and duplicate keys/tables are a parse error) and no
# TOML-capable tool is guaranteed on a Codex-only machine. CORE content is
# therefore wrapped in a managed block and written only when provably safe:
#   - file absent             -> write the managed block as the whole file
#   - complete managed block  -> replace strictly between the markers, in place
#   - any other content       -> write a .dega-core sidecar, leave config.toml
#                                untouched, and print manual-merge instructions
# Both markers are required for in-place replacement, so a truncated
# single-marker file is treated as user content rather than having its tail cut.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
TEMPLATE="${REPO_ROOT}/settings-template.json"

CODEX_DIR="${HOME}/.codex"
CONFIG_FILE="${CODEX_DIR}/config.toml"
SIDECAR_FILE="${CONFIG_FILE}.dega-core"
HOOKS_FILE="${CODEX_DIR}/hooks.json"

START_MARKER="# >>> dega-core managed >>>"
END_MARKER="# <<< dega-core managed <<<"

if [[ ! -f "${TEMPLATE}" ]]; then
  echo "error: settings-template.json not found at ${TEMPLATE}" >&2
  exit 1
fi

if ! command -v jq >/dev/null 2>&1; then
  echo "error: jq is required but not installed" >&2
  exit 1
fi

mkdir -p "${CODEX_DIR}"

# --- Build the managed config.toml block ---
# Laid out root-key-first (model_instructions_file, then [features], then
# [mcp_servers.*]) so the block is valid TOML on its own and never appends a
# root key after a table.
BLOCK_FILE="$(mktemp)"
trap 'rm -f "${BLOCK_FILE}"' EXIT

{
  printf '%s\n' "${START_MARKER}"
  cat <<'HEADER'
# Generated by dega-core codex adapter — do not edit between the markers.
# Re-run the adapter to regenerate this block.

model_instructions_file = "AGENTS.md"

[features]
codex_hooks = true

HEADER

  # Emit each MCP server as a TOML table
  jq -r '
    .mcpServers | to_entries[] |
    "[mcp_servers.\(.key)]",
    "command = \"\(.value.command)\"",
    (if .value.args then
      "args = [\(.value.args | map("\"" + . + "\"") | join(", "))]"
    else empty end),
    (if .value.env then
      "",
      "[mcp_servers.\(.key).env]",
      (.value.env | to_entries[] |
        "\(.key) = \"\(.value)\""
      )
    else empty end),
    ""
  ' "${TEMPLATE}"

  printf '%s\n' "${END_MARKER}"
} >"${BLOCK_FILE}"

# --- Write config.toml safely ---
if [[ ! -f "${CONFIG_FILE}" ]]; then
  # No existing file: the managed block is the whole file. Valid TOML.
  cp "${BLOCK_FILE}" "${CONFIG_FILE}"
  echo "Generated ${CONFIG_FILE}"
elif grep -qF "${START_MARKER}" "${CONFIG_FILE}" && grep -qF "${END_MARKER}" "${CONFIG_FILE}"; then
  # Complete managed block present: replace only the text between the markers,
  # touching no user line outside the block. Cannot create duplicates.
  awk -v block_file="${BLOCK_FILE}" -v start="${START_MARKER}" -v end="${END_MARKER}" '
    $0 == start {
      while ((getline line < block_file) > 0) print line
      close(block_file)
      skipping = 1
      next
    }
    skipping && $0 == end { skipping = 0; next }
    skipping { next }
    { print }
  ' "${CONFIG_FILE}" >"${CONFIG_FILE}.tmp"
  mv "${CONFIG_FILE}.tmp" "${CONFIG_FILE}"
  echo "Updated dega-core managed block in ${CONFIG_FILE}"
else
  # User content with no complete managed block: do not touch config.toml.
  # Write a sidecar and tell the user how to merge by hand.
  cp "${BLOCK_FILE}" "${SIDECAR_FILE}"
  cat >&2 <<EOF
warning: ${CONFIG_FILE} already exists without a complete dega-core managed block.
  To avoid corrupting your Codex settings, dega-core wrote its config to:
    ${SIDECAR_FILE}
  Merge it by hand: paste the block (between the markers) into ${CONFIG_FILE}.
  Merge [features] and [mcp_servers.*] into your existing tables instead of
  re-declaring them (TOML forbids duplicate keys/tables), and keep root keys
  such as model_instructions_file above the first [table] header.
EOF
fi

# --- Generate hooks.json ---
# Codex hooks.json wraps hooks in {"hooks": {...}}. Codex uses the same event
# names as the canonical template, so no translation is needed (unlike Gemini).
# hooks.json is fully CORE-owned and is regenerated on every run.
jq '{
  hooks: (
    .hooks | to_entries | map({
      key: .key,
      value: .value
    }) | from_entries
  )
}' "${TEMPLATE}" >"${HOOKS_FILE}.tmp"

mv "${HOOKS_FILE}.tmp" "${HOOKS_FILE}"
echo "Generated ${HOOKS_FILE}"
