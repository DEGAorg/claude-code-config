#!/usr/bin/env bash
set -euo pipefail

# Codex settings adapter
# Reads settings-template.json and generates two files for ~/.codex/:
#   config.toml  — MCP servers, model config, feature flags
#   hooks.json   — lifecycle hooks (Codex uses the same event names as Claude)

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
TEMPLATE="${REPO_ROOT}/settings-template.json"

CODEX_DIR="${HOME}/.codex"
CONFIG_FILE="${CODEX_DIR}/config.toml"
HOOKS_FILE="${CODEX_DIR}/hooks.json"

if [[ ! -f "${TEMPLATE}" ]]; then
	echo "error: settings-template.json not found at ${TEMPLATE}" >&2
	exit 1
fi

if ! command -v jq >/dev/null 2>&1; then
	echo "error: jq is required but not installed" >&2
	exit 1
fi

mkdir -p "${CODEX_DIR}"

# --- Generate config.toml ---
# Convert mcpServers from JSON to TOML [mcp_servers.<name>] tables.
# Enable codex_hooks feature flag so hooks.json is loaded.

{
	cat <<'HEADER'
# Generated by dega-core codex adapter — do not edit manually.
# Re-run the adapter to regenerate from settings-template.json.

model_instructions_file = "AGENTS.md"

[features]
codex_hooks = true

HEADER

	# Emit each MCP server as a TOML table
	jq -r '
    .mcpServers | to_entries[] |
    "[mcp_servers.\(.key)]",
    "command = \"\(.value.command)\"",
    (if .value.args then
      "args = [\(.value.args | map("\"" + . + "\"") | join(", "))]"
    else empty end),
    (if .value.env then
      "",
      "[mcp_servers.\(.key).env]",
      (.value.env | to_entries[] |
        "\(.key) = \"\(.value)\""
      )
    else empty end),
    ""
  ' "${TEMPLATE}"
} >"${CONFIG_FILE}.tmp"

mv "${CONFIG_FILE}.tmp" "${CONFIG_FILE}"
echo "Generated ${CONFIG_FILE}"

# --- Generate hooks.json ---
# Codex hooks.json wraps hooks in {"hooks": {...}}.
# Codex uses the same event names as the canonical template, so no
# translation is needed (unlike Gemini).

jq '{
  hooks: (
    .hooks | to_entries | map({
      key: .key,
      value: .value
    }) | from_entries
  )
}' "${TEMPLATE}" >"${HOOKS_FILE}.tmp"

mv "${HOOKS_FILE}.tmp" "${HOOKS_FILE}"
echo "Generated ${HOOKS_FILE}"
