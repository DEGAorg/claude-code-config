#!/usr/bin/env bash
set -euo pipefail

# Codex settings adapter
# Reads settings-template.json and generates two files for ~/.codex/:
#   config.toml  — MCP servers, model config, feature flags
#   hooks.json   — lifecycle hooks (Codex uses the same event names as Claude)
#
# config.toml is merged, not overwritten: all CORE-owned content lives between
# the managed-block markers below. User keys outside the block are preserved
# across re-runs. If a user hand-authors a key CORE also defines, CORE's value
# wins inside the managed block and the user copy outside the block is left
# intact. hooks.json is fully CORE-owned and regenerated each run.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
TEMPLATE="${REPO_ROOT}/settings-template.json"

CODEX_DIR="${HOME}/.codex"
CONFIG_FILE="${CODEX_DIR}/config.toml"
HOOKS_FILE="${CODEX_DIR}/hooks.json"

MARKER_START="# >>> dega-core managed >>>"
MARKER_END="# <<< dega-core managed <<<"

if [[ ! -f "${TEMPLATE}" ]]; then
  echo "error: settings-template.json not found at ${TEMPLATE}" >&2
  exit 1
fi

if ! command -v jq >/dev/null 2>&1; then
  echo "error: jq is required but not installed" >&2
  exit 1
fi

mkdir -p "${CODEX_DIR}"

# --- Build the CORE-managed config.toml block ---
# Convert mcpServers from JSON to TOML [mcp_servers.<name>] tables.
# Enable the codex_hooks feature flag so hooks.json is loaded.

BLOCK_FILE="$(mktemp)"
trap 'rm -f "${BLOCK_FILE}"' EXIT

{
  echo "${MARKER_START}"
  cat <<'HEADER'
# Generated by dega-core codex adapter — do not edit inside this block.
# Re-run the adapter to regenerate. User keys outside this block are preserved.

model_instructions_file = "AGENTS.md"

[features]
codex_hooks = true

HEADER

  # Emit each MCP server as a TOML table
  jq -r '
    .mcpServers | to_entries[] |
    "[mcp_servers.\(.key)]",
    "command = \"\(.value.command)\"",
    (if .value.args then
      "args = [\(.value.args | map("\"" + . + "\"") | join(", "))]"
    else empty end),
    (if .value.env then
      "",
      "[mcp_servers.\(.key).env]",
      (.value.env | to_entries[] |
        "\(.key) = \"\(.value)\""
      )
    else empty end),
    ""
  ' "${TEMPLATE}"
  echo "${MARKER_END}"
} >"${BLOCK_FILE}"

# --- Merge the block into config.toml, preserving user keys ---
if [[ -f "${CONFIG_FILE}" ]] && grep -qF "${MARKER_START}" "${CONFIG_FILE}"; then
  # Replace the existing managed block in place; leave all other lines untouched.
  awk -v start="${MARKER_START}" -v end="${MARKER_END}" -v blockfile="${BLOCK_FILE}" '
    $0 == start {
      while ((getline line < blockfile) > 0) print line
      close(blockfile)
      skip = 1
      next
    }
    $0 == end { skip = 0; next }
    !skip { print }
  ' "${CONFIG_FILE}" >"${CONFIG_FILE}.tmp"
  mv "${CONFIG_FILE}.tmp" "${CONFIG_FILE}"
else
  # No managed block yet: append it, keeping any existing user content above.
  if [[ -s "${CONFIG_FILE}" ]]; then
    printf '\n' >>"${CONFIG_FILE}"
  fi
  cat "${BLOCK_FILE}" >>"${CONFIG_FILE}"
fi

echo "Generated ${CONFIG_FILE}"

# --- Generate hooks.json ---
# Codex hooks.json wraps hooks in {"hooks": {...}}.
# Codex uses the same event names as the canonical template, so no
# translation is needed (unlike Gemini).

jq '{
  hooks: (
    .hooks | to_entries | map({
      key: .key,
      value: .value
    }) | from_entries
  )
}' "${TEMPLATE}" >"${HOOKS_FILE}.tmp"

mv "${HOOKS_FILE}.tmp" "${HOOKS_FILE}"
echo "Generated ${HOOKS_FILE}"
